@dataclass
class GPUHealthTelemetry:
    """Snapshot of real-time GPU hardware signals collected via DCGM and host drivers."""

    host_id: str
    gpu_index: int
    temperature_celsius: float
    power_watts: float
    pcie_generation: int
    pcie_link_width: int
    correctable_ecc_errors: int = 0
    uncorrectable_ecc_errors: int = 0
    nvlink_packet_drop_rate: float = 0.0
    active_xid_codes: List[int] = field(default_factory=list)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass
class AnomalyDetectionResult:
    """Synthesized anomaly verdict for a single GPU or host node."""

    is_anomalous: bool
    severity: GPUFailureSeverity
    host_id: str
    gpu_index: Optional[int]
    triggered_rules: List[str]
    identified_xids: List[XidErrorDefinition]
    recommended_action: HardwareResetType
    confidence: float


@dataclass
class IncidentDiagnosis:
    """Root cause investigation generated by the Infra Investigator Agent."""

    incident_id: str
    host_id: str
    datacenter: str
    rack_id: str
    root_cause_hypothesis: str
    severity: GPUFailureSeverity
    affected_gpus: List[int]
    affected_jobs: List[str]
    blast_radius_summary: str
    recommended_remediation: HardwareResetType
    confidence_score: float
    investigation_notes: List[str]
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass
class RevalidationMetrics:
    """Pre-flight and post-remediation benchmarks for compute re-entry."""

    passed: bool
    gpu_memory_bandwidth_gbps: float
    nccl_allreduce_bus_bandwidth_gbps: float
    pcie_bidirectional_bandwidth_gbps: float
    detected_errors: List[str] = field(default_factory=list)


@dataclass
class RemediationExecutionResult:
    """Outcome of an autonomous cordon, drain, reset, and revalidation loop."""

    execution_id: str
    host_id: str
    action_taken: HardwareResetType
    node_previous_state: NodeLifecycleState
    node_final_state: NodeLifecycleState
    drained_job_count: int
    revalidation: RevalidationMetrics
    escalated_to_oncall: bool
    resolution_summary: str
    execution_duration_sec: float


class GPUFleetKnowledgeGraph:
    """Knowledge graph modeling datacenter topology, rack interconnects, and running jobs."""

    def __init__(self) -> None:
        self.hosts: Dict[str, Dict[str, Any]] = {}
        self.gpus: Dict[str, Dict[str, Any]] = {}
        self.jobs: Dict[str, Set[str]] = {}  # job_id -> set of host_ids
        self.rack_topology: Dict[str, Set[str]] = {}  # rack_id -> set of host_ids
        self.datacenter_topology: Dict[str, Set[str]] = {}  # dc -> set of rack_ids

    def register_host(
        self,
        host_id: str,
        datacenter: str,
        rack_id: str,
        gpu_count: int = 8,
        gpu_model: str = "NVIDIA-H100-SXM5-80GB",
    ) -> None:
        """Register a physical GPU host within the cluster topology."""
        self.hosts[host_id] = {
            "datacenter": datacenter,
            "rack_id": rack_id,
            "gpu_count": gpu_count,
            "gpu_model": gpu_model,
            "state": NodeLifecycleState.ACTIVE,
            "registered_at": datetime.now(timezone.utc),
        }
        self.rack_topology.setdefault(rack_id, set()).add(host_id)
        self.datacenter_topology.setdefault(datacenter, set()).add(rack_id)

        for i in range(gpu_count):
            gpu_id = f"{host_id}:gpu:{i}"
            self.gpus[gpu_id] = {
                "host_id": host_id,
                "gpu_index": i,
                "model": gpu_model,
                "healthy": True,
            }

    def allocate_job(self, job_id: str, host_ids: List[str]) -> None:
        """Associate a distributed training or inference job across a set of hosts."""
        for hid in host_ids:
            if hid not in self.hosts:
                raise ValueError(f"Host {hid} not found in knowledge graph.")
        self.jobs[job_id] = set(host_ids)

    def set_host_state(self, host_id: str, state: NodeLifecycleState) -> None:
        """Transition the scheduler lifecycle state of a host."""
        if host_id not in self.hosts:
            raise KeyError(f"Host {host_id} not registered.")
        self.hosts[host_id]["state"] = state

    def get_host_state(self, host_id: str) -> NodeLifecycleState:
        """Retrieve the current lifecycle state of a host."""
        if host_id not in self.hosts:
            raise KeyError(f"Host {host_id} not registered.")
        return self.hosts[host_id]["state"]

    def find_affected_jobs(self, host_id: str) -> List[str]:
        """Find all active distributed jobs running on or dependent upon a host."""
        affected: List[str] = []
        for job_id, allocated_hosts in self.jobs.items():
            if host_id in allocated_hosts:
                affected.append(job_id)
        return affected

    def compute_blast_radius(self, host_id: str) -> Dict[str, Any]:
        """Calculate the failure domain and blast radius for a degraded host."""
        if host_id not in self.hosts:
            raise KeyError(f"Host {host_id} not registered.")

        host_meta = self.hosts[host_id]
        rack_id = host_meta["rack_id"]
        dc = host_meta["datacenter"]
        neighbors = self.rack_topology.get(rack_id, set()) - {host_id}
        affected_jobs = self.find_affected_jobs(host_id)

        return {
            "host_id": host_id,
            "datacenter": dc,
            "rack_id": rack_id,
            "rack_neighbor_count": len(neighbors),
            "affected_job_count": len(affected_jobs),
            "affected_jobs": affected_jobs,
        }


class GPUAnomalyDetector:
    """Rule and threshold evaluation engine for real-time GPU telemetry."""

    def __init__(
        self,
        max_temp_celsius: float = 85.0,
        expected_pcie_gen: int = 5,
        expected_pcie_width: int = 16,
        max_nvlink_drop_rate: float = 0.05,
    ) -> None:
        self.max_temp_celsius = max_temp_celsius
        self.expected_pcie_gen = expected_pcie_gen
        self.expected_pcie_width = expected_pcie_width
        self.max_nvlink_drop_rate = max_nvlink_drop_rate

    def evaluate_telemetry(self, telemetry: GPUHealthTelemetry) -> AnomalyDetectionResult:
        """Analyze a telemetry sample for physical degradations and Xid faults."""
        triggered: List[str] = []
        identified_xids: List[XidErrorDefinition] = []
        highest_severity = GPUFailureSeverity.TRANSIENT
        recommended_action = HardwareResetType.SOFT_GPU_RESET

        # 1. Evaluate NVIDIA Xid errors
        for code in telemetry.active_xid_codes:
            xid_def = CANONICAL_XID_CATALOG.get(code)
            if xid_def:
                identified_xids.append(xid_def)
                triggered.append(f"Xid {xid_def.xid_code}: {xid_def.name}")
                if xid_def.severity == GPUFailureSeverity.FATAL:
                    highest_severity = GPUFailureSeverity.FATAL
                    recommended_action = xid_def.recommended_action
                elif xid_def.severity == GPUFailureSeverity.CRITICAL and highest_severity != GPUFailureSeverity.FATAL:
                    highest_severity = GPUFailureSeverity.CRITICAL
                    recommended_action = xid_def.recommended_action
                elif (
                    xid_def.severity == GPUFailureSeverity.WARNING
                    and highest_severity == GPUFailureSeverity.TRANSIENT
                ):
                    highest_severity = GPUFailureSeverity.WARNING
                    recommended_action = xid_def.recommended_action
            else:
                triggered.append(f"Unknown Xid Code {code}")
                if highest_severity == GPUFailureSeverity.TRANSIENT:
                    highest_severity = GPUFailureSeverity.WARNING

        # 2. Check PCIe link width degradation
        if telemetry.pcie_generation < self.expected_pcie_gen or telemetry.pcie_link_width < self.expected_pcie_width:
            triggered.append(
                f"PCIe link degraded: Gen{telemetry.pcie_generation}x{telemetry.pcie_link_width} "
                f"(expected Gen{self.expected_pcie_gen}x{self.expected_pcie_width})"
            )
            if highest_severity in (GPUFailureSeverity.TRANSIENT, GPUFailureSeverity.WARNING):
                highest_severity = GPUFailureSeverity.CRITICAL
                recommended_action = HardwareResetType.PCI_BUS_RESCAN

        # 3. Check thermal throttling
        if telemetry.temperature_celsius >= self.max_temp_celsius:
            triggered.append(
                f"Thermal threshold exceeded: {telemetry.temperature_celsius}°C >= {self.max_temp_celsius}°C"
            )
            if highest_severity == GPUFailureSeverity.TRANSIENT:
                highest_severity = GPUFailureSeverity.WARNING

        # 4. Check NVLink packet drops
        if telemetry.nvlink_packet_drop_rate >= self.max_nvlink_drop_rate:
            triggered.append(
                f"NVLink drop rate elevated: {telemetry.nvlink_packet_drop_rate:.3f} >= {self.max_nvlink_drop_rate:.3f}"
            )
            if highest_severity in (GPUFailureSeverity.TRANSIENT, GPUFailureSeverity.WARNING):
                highest_severity = GPUFailureSeverity.WARNING

        # 5. Check Uncorrectable ECC
        if telemetry.uncorrectable_ecc_errors > 0:
            triggered.append(f"Uncorrectable ECC memory errors: {telemetry.uncorrectable_ecc_errors}")
            highest_severity = GPUFailureSeverity.FATAL
            recommended_action = HardwareResetType.PHYSICAL_DRAIN_RMA

        is_anomalous = len(triggered) > 0
        confidence = 0.98 if identified_xids else (0.85 if is_anomalous else 0.0)

        return AnomalyDetectionResult(
            is_anomalous=is_anomalous,
            severity=highest_severity if is_anomalous else GPUFailureSeverity.TRANSIENT,
            host_id=telemetry.host_id,
            gpu_index=telemetry.gpu_index,
            triggered_rules=triggered,
            identified_xids=identified_xids,
            recommended_action=recommended_action,
            confidence=confidence,
        )


class InfraInvestigatorAgent:
    """Agent that correlates telemetry anomalies against fleet topology and history."""

    def __init__(self, knowledge_graph: GPUFleetKnowledgeGraph) -> None:
        self.kg = knowledge_graph

    def investigate(self, host_id: str, anomalies: List[AnomalyDetectionResult]) -> IncidentDiagnosis:
        """Perform topological incident correlation and root-cause synthesis."""
        if host_id not in self.kg.hosts:
            raise KeyError(f"Host {host_id} not found in knowledge graph.")

        host_meta = self.kg.hosts[host_id]
        dc = host_meta["datacenter"]
        rack_id = host_meta["rack_id"]

        affected_gpus: List[int] = []
        highest_severity = GPUFailureSeverity.TRANSIENT
        recommended_action = HardwareResetType.SOFT_GPU_RESET
        investigation_notes: List[str] = []

        has_xid_79 = False
        has_uncorrectable_ecc = False

        for anomaly in anomalies:
            if anomaly.gpu_index is not None and anomaly.gpu_index not in affected_gpus:
                affected_gpus.append(anomaly.gpu_index)

            for xid in anomaly.identified_xids:
                investigation_notes.append(
                    f"GPU {anomaly.gpu_index}: Identified Xid {xid.xid_code} - {xid.description}"
                )
                if xid.xid_code == 79:
                    has_xid_79 = True
                if xid.xid_code == 92:
                    has_uncorrectable_ecc = True

            if anomaly.severity == GPUFailureSeverity.FATAL:
                highest_severity = GPUFailureSeverity.FATAL
                recommended_action = anomaly.recommended_action
            elif anomaly.severity == GPUFailureSeverity.CRITICAL and highest_severity != GPUFailureSeverity.FATAL:
                highest_severity = GPUFailureSeverity.CRITICAL
                recommended_action = anomaly.recommended_action

        # Synthesize hypothesis based on multi-signal correlation
        if has_uncorrectable_ecc:
            hypothesis = "Fatal hardware SRAM/HBM uncorrectable degradation; node requires physical maintenance RMA."
            recommended_action = HardwareResetType.PHYSICAL_DRAIN_RMA
            confidence = 0.99
        elif has_xid_79:
            hypothesis = (
                "GPU fallen off PCIe bus (Xid 79); host requires cold power cycle via BMC to recover interface."
            )
            recommended_action = HardwareResetType.BMC_POWER_CYCLE
            confidence = 0.96
        elif len(affected_gpus) >= 4:
            hypothesis = "Multi-GPU bus or baseboard power/NVLink failure; rack switch or host BMC reboot indicated."
            recommended_action = HardwareResetType.BMC_POWER_CYCLE
            confidence = 0.92
        elif len(affected_gpus) > 0:
            hypothesis = f"Isolated engine or driver fault on GPU {affected_gpus}; recoverable via driver/PCI reload."
            confidence = 0.88
        else:
            hypothesis = "No hardware faults detected across host devices."
            confidence = 1.0

        blast_radius = self.kg.compute_blast_radius(host_id)
        affected_jobs = blast_radius["affected_jobs"]

        summary = (
            f"Host {host_id} in {dc}/{rack_id} has {len(affected_gpus)} degraded GPUs, "
            f"impacting {len(affected_jobs)} running jobs."
        )

        return IncidentDiagnosis(
            incident_id=f"INC-{host_id}-{int(datetime.now(timezone.utc).timestamp())}",
            host_id=host_id,
            datacenter=dc,
            rack_id=rack_id,
            root_cause_hypothesis=hypothesis,
            severity=highest_severity,
            affected_gpus=sorted(affected_gpus),
            affected_jobs=affected_jobs,
            blast_radius_summary=summary,
            recommended_remediation=recommended_action,
            confidence_score=confidence,
            investigation_notes=investigation_notes,
        )


class AutonomousRemediationEngine:
    """Orchestrates node cordoning, job draining, hardware resets, and NCCL pre-flight revalidation."""

    def __init__(
        self,
        knowledge_graph: GPUFleetKnowledgeGraph,
        min_healthy_nccl_bandwidth_gbps: float = 350.0,
        min_healthy_memory_bandwidth_gbps: float = 2400.0,
    ) -> None:
        self.kg = knowledge_graph
        self.min_healthy_nccl_bandwidth_gbps = min_healthy_nccl_bandwidth_gbps
        self.min_healthy_memory_bandwidth_gbps = min_healthy_memory_bandwidth_gbps

    def execute_remediation(
        self,
        diagnosis: IncidentDiagnosis,
        simulate_hardware_success: bool = True,
    ) -> RemediationExecutionResult:
        """Run the full autonomous remediation and revalidation cycle."""
        host_id = diagnosis.host_id
        prev_state = self.kg.get_host_state(host_id)
        action = diagnosis.recommended_remediation

        # Step 1: Cordon the node
        self.kg.set_host_state(host_id, NodeLifecycleState.CORDONED)

        # Step 2: Drain running workloads
        self.kg.set_host_state(host_id, NodeLifecycleState.DRAINING)
        drained_jobs = self.kg.find_affected_jobs(host_id)
        # Evict jobs from knowledge graph
        for jid in drained_jobs:
            if jid in self.kg.jobs:
                del self.kg.jobs[jid]

        # Step 3: Execute hardware reset action
        self.kg.set_host_state(host_id, NodeLifecycleState.REMEDIATING)

        # Step 4: Revalidate node health
        self.kg.set_host_state(host_id, NodeLifecycleState.REVALIDATING)
        reval = self._run_revalidation(simulate_hardware_success, action)

        # Step 5: Post-revalidation state transition
        if reval.passed:
            self.kg.set_host_state(host_id, NodeLifecycleState.ACTIVE)
            final_state = NodeLifecycleState.ACTIVE
            escalated = False
            summary = (
                f"Autonomous remediation {action.value} succeeded on {host_id}. "
                f"NCCL all-reduce revalidation passed ({reval.nccl_allreduce_bus_bandwidth_gbps:.1f} GB/s). "
                f"Node returned to ACTIVE pool."
            )
        else:
            self.kg.set_host_state(host_id, NodeLifecycleState.MAINTENANCE)
            final_state = NodeLifecycleState.MAINTENANCE
            escalated = True
            summary = (
                f"Remediation {action.value} failed revalidation on {host_id}: {', '.join(reval.detected_errors)}. "
                f"Node marked for datacenter on-call MAINTENANCE."
            )

        return RemediationExecutionResult(
            execution_id=f"REM-{host_id}-{int(datetime.now(timezone.utc).timestamp())}",
            host_id=host_id,
            action_taken=action,
            node_previous_state=prev_state,
            node_final_state=final_state,
            drained_job_count=len(drained_jobs),
            revalidation=reval,
            escalated_to_oncall=escalated,
            resolution_summary=summary,
            execution_duration_sec=14.2,
        )

    def _run_revalidation(
        self,
        simulate_hardware_success: bool,
        action: HardwareResetType,
    ) -> RevalidationMetrics:
        """Simulate pre-flight NCCL and memory bandwidth verification tests."""
        if not simulate_hardware_success or action == HardwareResetType.PHYSICAL_DRAIN_RMA:
            return RevalidationMetrics(
                passed=False,
                gpu_memory_bandwidth_gbps=800.0,
                nccl_allreduce_bus_bandwidth_gbps=120.0,
                pcie_bidirectional_bandwidth_gbps=12.0,
                detected_errors=[
                    "NCCL bus bandwidth below threshold (120 GB/s < 350 GB/s)",
                    "Persistent memory errors",
                ],
            )

        return RevalidationMetrics(
            passed=True,
            gpu_memory_bandwidth_gbps=3200.0,
            nccl_allreduce_bus_bandwidth_gbps=420.0,
            pcie_bidirectional_bandwidth_gbps=58.0,
            detected_errors=[],
        )
