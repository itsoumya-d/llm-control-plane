"""Together AI Infra Agent Systems: GPU fleet telemetry knowledge graph and remediation.

Built for large-scale GPU infrastructure operations (NVIDIA H100/H200/B200 clusters),
providing autonomous incident investigation, Xid error correlation, and self-revalidating node repair.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional, Set


class GPUFailureSeverity(str, Enum):
    """Classification of GPU hardware and cluster fault severity."""

    TRANSIENT = "transient"
    WARNING = "warning"
    CRITICAL = "critical"
    FATAL = "fatal"


class NodeLifecycleState(str, Enum):
    """Lifecycle state of a GPU compute host in the cluster scheduler."""

    ACTIVE = "active"
    CORDONED = "cordoned"
    DRAINING = "draining"
    REMEDIATING = "remediating"
    REVALIDATING = "revalidating"
    MAINTENANCE = "maintenance"


class HardwareResetType(str, Enum):
    """Remediation action dispatched to degraded infrastructure."""

    SOFT_GPU_RESET = "soft_gpu_reset"
    DRIVER_RELOAD = "driver_reload"
    PCI_BUS_RESCAN = "pci_bus_rescan"
    BMC_POWER_CYCLE = "bmc_power_cycle"
    PHYSICAL_DRAIN_RMA = "physical_drain_rma"


